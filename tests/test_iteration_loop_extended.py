import pytest

from ghostwriter.chapter import run_pipelines_for_chapter
from ghostwriter.context import UserActionRequired


def _copy_book(src: Path, dst: Path) -> None:
    if dst.exists():
        shutil.rmtree(dst, ignore_errors=True)
    shutil.copytree(src, dst)


@pytest.fixture()
def sandbox_book(tmp_path: Path, lr_source_dir: Path) -> Path:
    dst = tmp_path / "book"
    _copy_book(lr_source_dir, dst)
    return dst


def _strip_done(brainstorm: Path) -> None:
    if not brainstorm.exists():
        return
    lines = brainstorm.read_text(encoding="utf-8").splitlines()
    while lines and not lines[-1].strip():
        lines.pop()
    if lines and lines[-1].strip().lower().startswith("done"):
        lines.pop()
    brainstorm.write_text("\n".join(lines).rstrip() + ("\n" if lines else ""), encoding="utf-8")


def _reset_versions(iter_root: Path) -> None:
    # Remove any versioned chapter-level files so latest=0 and branch_b=False
    for pref in ("draft", "check", "suggestions", "pre_draft"):
        for p in iter_root.glob(f"{pref}_v*.txt"):
            try:
                p.unlink()
            except Exception:
                pass
    # Drop later pipelines to avoid interference
    for d in (iter_root / "pipeline_v2", iter_root / "pipeline_v3"):
        if d.exists():
            shutil.rmtree(d, ignore_errors=True)


def _run_until(chapter_path: Path, version: int, predicate, max_runs: int = 12) -> None:
    """Run pipelines repeatedly (catching human-in-loop pauses) until predicate() is True or max_runs exhausted."""
    for _ in range(max_runs):
        try:
            run_pipelines_for_chapter(str(chapter_path), version, log_llm=False)
        except UserActionRequired:
            pass
        if predicate():
            return
    raise AssertionError(f"Predicate not satisfied after {max_runs} runs for version {version}.")


def test_brainstorm_requires_done_for_multiple_types(monkeypatch: pytest.MonkeyPatch, sandbox_book: Path):
    monkeypatch.setenv("GW_BOOK_BASE_DIR", str(sandbox_book))
    monkeypatch.setenv("GW_USE_MOCK_LLM", "1")
    monkeypatch.setenv("GW_MOCKLLM_FALLBACK", "0")

    chapter_path = sandbox_book / "chapters/CHAPTER_001.yaml"
    assert chapter_path.exists()

    # Ensure a fresh v1 authoring run (no prior drafts) so brainstorm gating applies
    iter_root = sandbox_book / "iterations/CHAPTER_001"
    _reset_versions(iter_root)
    # Select representative step dirs for narration, dialog, mixed (skip if missing to avoid false failures)
    base_iter = sandbox_book / "iterations/CHAPTER_001/pipeline_v1"
    candidates = ["05_narration", "06_dialog", "06_mixed", "07_scene", "09_narration"]
    tested_any = False
    # Run once to allow resume scan to populate; tolerate HIL pauses
    try:
        run_pipelines_for_chapter(str(chapter_path), 1, log_llm=False)
    except UserActionRequired:
        pass
    for name in candidates:
        step_dir = base_iter / name
        bs = step_dir / "brainstorm.txt"
        if not bs.exists():
            continue
        tested_any = True
        existing = bs.read_text(encoding="utf-8")
        if existing.strip().upper().endswith("DONE"):
            # Remove DONE and trigger a gated pause
            _strip_done(bs)
            # Run until we observe a pause generated by this brainstorm (indicated by appended resume file without DONE)
            def _brainstorm_incomplete():
                txt = bs.read_text(encoding="utf-8") if bs.exists() else ""
                return txt.strip() and not txt.strip().upper().endswith("DONE")
            _run_until(chapter_path, 1, _brainstorm_incomplete)
            # Restore DONE and resume
            with bs.open("a", encoding="utf-8") as f:
                f.write("DONE\n")
            _run_until(chapter_path, 1, lambda: bs.read_text(encoding="utf-8").strip().upper().endswith("DONE"))
    assert tested_any, "No brainstorm.txt found among expected step directories; test inconclusive."


def test_stop_after_first_suggestions_then_resume(monkeypatch: pytest.MonkeyPatch, sandbox_book: Path):
    monkeypatch.setenv("GW_BOOK_BASE_DIR", str(sandbox_book))
    monkeypatch.setenv("GW_USE_MOCK_LLM", "1")
    monkeypatch.setenv("GW_MOCKLLM_FALLBACK", "0")
    chapter_path = sandbox_book / "chapters/CHAPTER_001.yaml"
    assert chapter_path.exists()

    # Ensure fresh v1 run context
    _reset_versions(sandbox_book / "iterations/CHAPTER_001")
    # Pick the first contentful step (narration/dialog/implicit/mixed)
    base_iter = sandbox_book / "iterations/CHAPTER_001/pipeline_v1"
    gate_dir = None
    for child in sorted(base_iter.iterdir()):
        if not child.is_dir():
            continue
        if child.name.endswith(("narration", "dialog", "implicit", "mixed")):
            gate_dir = child
            break
    assert gate_dir is not None
    first_draft = gate_dir / "touch_point_first_draft.txt"
    first_suggestions = gate_dir / "first_suggestions.txt"
    final_draft = gate_dir / "touch_point_draft.txt"
    suggestions = gate_dir / "suggestions.txt"
    assert gate_dir.exists()

    # Simulate pre-gate state by removing only gate files (leave final draft & suggestions intact for regeneration path)
    for p in (first_draft, first_suggestions):
        if p.exists():
            p.unlink()

    # First run should create first gate files (initial authoring) and stop gracefully
    # Advance runs until gate files for this step appear
    _run_until(chapter_path, 1, lambda: first_draft.exists() and first_suggestions.exists())
    assert not final_draft.exists() and not suggestions.exists()

    # Resume: create subtle edit outputs by re-running (should not raise now)
    try:
        run_pipelines_for_chapter(str(chapter_path), 1, log_llm=False)
    except UserActionRequired:
        run_pipelines_for_chapter(str(chapter_path), 1, log_llm=False)
    assert final_draft.exists() and suggestions.exists()


def test_version2_full_sweep_and_no_version3(monkeypatch: pytest.MonkeyPatch, sandbox_book: Path):
    monkeypatch.setenv("GW_BOOK_BASE_DIR", str(sandbox_book))
    monkeypatch.setenv("GW_USE_MOCK_LLM", "1")
    monkeypatch.setenv("GW_MOCKLLM_FALLBACK", "0")
    chapter_path = sandbox_book / "chapters/CHAPTER_001.yaml"
    assert chapter_path.exists()

    # Remove any pre-existing pipeline_v3 to verify we don't create it when running v2
    pv3 = sandbox_book / "iterations/CHAPTER_001/pipeline_v3"
    if pv3.exists():
        shutil.rmtree(pv3, ignore_errors=True)
    # Ensure v1 artifacts exist (resume flow) by running initial authoring to gate pause then resume fully
    try:
        run_pipelines_for_chapter(str(chapter_path), 1, log_llm=False)
    except UserActionRequired:
        # Resume to complete v1
        run_pipelines_for_chapter(str(chapter_path), 1, log_llm=False)

    # Run v2 – branch_b True, should produce subtle edit drafts directly for contentful steps without gate pause
    run_pipelines_for_chapter(str(chapter_path), 2, log_llm=False)
    pipe_v2 = sandbox_book / "iterations/CHAPTER_001/pipeline_v2"
    assert pipe_v2.exists()
    # Ensure at least one contentful step has a final draft
    any_draft = list(pipe_v2.rglob("touch_point_draft.txt"))
    assert any_draft, "Expected subtle edit drafts in v2 pipeline"
    # No pipeline_v3 should be created by running v2
    assert not (sandbox_book / "iterations/CHAPTER_001/pipeline_v3").exists()


